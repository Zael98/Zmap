"""Generates Data/Npcs.lua: every NPC of WoW Forever that Warcraft DB (forever.warcraftdb.com) knows where it
stands: name, title, level, the services it offers (innkeeper, vendor, trainer...), who it is friendly to,
whether it is rare or elite, and its spawn points on the zone maps. It feeds Zmap's NPC search, the
townsfolk layer and the rares layer.

    python tools/build_npcs.py            (downloads what is not cached in tools/cache/wdb; ~7000 pages)

Names come in English; in game Zmap learns each NPC's name in the client's language (Modules/Npcs.lua).
The site's certificate does not verify on some machines, so it is fetched without verifying it (public
data, nothing is sent)."""
import json
import re
import ssl
import sys
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = Path(__file__).resolve().parent / "cache" / "wdb"
SITE = "https://forever.warcraftdb.com"
CTX = ssl.create_default_context()
CTX.check_hostname = False
CTX.verify_mode = ssl.CERT_NONE
MAX_SPAWNS = 24          # an NPC standing in many places (a mob, the spirit healers) keeps this many

# services, in the order of the flag bits Modules/Npcs.lua reads
SERVICES = ["Innkeeper", "Vendor", "Repair", "Trainer", "Flight Master", "Banker", "Auctioneer", "Stable Master",
            "Spirit Healer", "Battlemaster", "Guild Banker", "Mailbox"]


def get(path, cache):
    if cache.exists():
        return json.loads(cache.read_text(encoding="utf-8"))
    cache.parent.mkdir(parents=True, exist_ok=True)
    for attempt in range(5):
        try:
            req = urllib.request.Request(SITE + path, headers={"User-Agent": "Mozilla/5.0 (Zmap build_npcs)"})
            raw = urllib.request.urlopen(req, timeout=60, context=CTX).read().decode("utf-8")
            data = json.loads(raw)
            cache.write_text(raw, encoding="utf-8")
            time.sleep(0.15)   # (be gentle with the site)
            return data
        except urllib.error.HTTPError as e:
            if e.code == 404:
                cache.write_text("null", encoding="utf-8")
                return None
            time.sleep(2 + attempt * 3)
        except Exception:
            time.sleep(2 + attempt * 3)
    raise RuntimeError(f"{path}: no answer")


def npc_ids():
    first = get("/api/data/list/npcs?page=1&per_page=100", CACHE / "list" / "1.json")
    ids = [r["record_id"] for r in first["rows"]]
    for page in range(2, first["pages"] + 1):
        ids += [r["record_id"] for r in get(f"/api/data/list/npcs?page={page}&per_page=100", CACHE / "list" / f"{page}.json")["rows"]]
    return ids


def strip(html):
    return re.sub(r"<[^>]+>", "", html or "").strip()


def parse(npc_id, node):
    if not node:
        return None
    data = node.get("data") or {}
    pins = ((node.get("extra") or {}).get("npc_map") or {}).get("pins") or []
    if not pins or not data.get("name"):
        return None
    services = [s.strip() for s in (data.get("services") or "").split(",") if s.strip()]
    flags = 0
    for i, s in enumerate(SERVICES):
        if s in services:
            flags |= 1 << i
    reaction = data.get("reaction") or ""
    friendly = set(re.findall(r"faction-(\w+)", reaction)) if "Friendly" in strip(reaction) else set()
    classification = (data.get("classification") or "").lower()
    level = re.findall(r"\d+", str(data.get("level") or ""))
    by_map = {}
    for p in pins:
        by_map.setdefault(p["ui_map_id"], []).append((p["u"], p["v"]))
    return {
        "id": npc_id, "name": data["name"], "title": data.get("title") or "", "flags": flags,
        "friendly": "".join(sorted(f[0].upper() for f in friendly)),   # "A", "H", "AH" or ""
        "rare": "rare" in classification, "elite": "elite" in classification,
        "level": "-".join(level[:2]) if level else "",
        "spawns": by_map,
    }


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ids = npc_ids()
    print(f"{len(ids)} NPCs listed")
    with ThreadPoolExecutor(4) as pool:
        nodes = list(pool.map(lambda i: get(f"/api/data/node/npc/{i}", CACHE / "npc" / f"{i}.json"), ids))
    npcs = [n for n in (parse(i, node) for i, node in zip(ids, nodes)) if n]
    print(f"{len(npcs)} with spawn points")
    lines = ["-- Generated by tools/build_npcs.py from Warcraft DB (forever.warcraftdb.com). Regenerate rather than edit.",
             "local _, ns = ...", "",
             "-- the services' flag bits, in order: " + ", ".join(SERVICES),
             "-- [npcID] = { name (English), title, flags, friendly to (A, H, AH or \"\"), level, rare (1) / elite (2),",
             "--             uiMapID, { x1, y1, x2, y2, ... } (per thousand of its map), another uiMapID, { ... }, ... }",
             "ns.NPCS = {"]
    for n in sorted(npcs, key=lambda n: n["id"]):
        rank = (1 if n["rare"] else 0) + (2 if n["elite"] else 0)
        parts, kept = [], 0
        for m, pts in sorted(n["spawns"].items(), key=lambda kv: -len(kv[1])):
            pts = pts[:max(0, MAX_SPAWNS - kept)]
            if not pts:
                break
            kept += len(pts)
            coords = ", ".join(f"{round(u * 1000)}, {round(v * 1000)}" for u, v in pts)
            parts.append(f"{m}, {{ {coords} }}")
        lines.append(f'    [{n["id"]}] = {{ {lua_str(n["name"])}, {lua_str(n["title"])}, {n["flags"]}, "{n["friendly"]}", '
                     f'"{n["level"]}", {rank}, {", ".join(parts)} }},')
    lines.append("}")
    (ROOT / "Data" / "Npcs.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    services = {}
    for n in npcs:
        for i, s in enumerate(SERVICES):
            if n["flags"] & (1 << i):
                services[s] = services.get(s, 0) + 1
    print("services:", services)
    print("rares:", sum(n["rare"] for n in npcs), "elites:", sum(n["elite"] for n in npcs))


if __name__ == "__main__":
    sys.exit(main())
